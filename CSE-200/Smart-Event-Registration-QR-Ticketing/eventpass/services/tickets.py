"""QR and printable PDF ticket generation (all generated in memory)."""

from io import BytesIO

import qrcode
from qrcode.constants import ERROR_CORRECT_H
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas
from reportlab.pdfbase.pdfmetrics import stringWidth

from .security import make_qr_payload


def build_qr_png(event, token: str) -> bytes:
    """Return a PNG QR code containing only the opaque ticket token payload."""
    payload = make_qr_payload(event.slug, token)
    qr = qrcode.QRCode(version=None, error_correction=ERROR_CORRECT_H, box_size=10, border=4)
    qr.add_data(payload)
    qr.make(fit=True)
    image = qr.make_image(fill_color="#102a43", back_color="white").convert("RGB")
    buffer = BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def _fit_text(value: str, max_width: float, font_name: str = "Helvetica", font_size: int = 9) -> str:
    text = str(value or "")
    if stringWidth(text, font_name, font_size) <= max_width:
        return text
    while text and stringWidth(text + "...", font_name, font_size) > max_width:
        text = text[:-1]
    return text + "..."


def generate_ticket_pdf(registration, event, token: str) -> bytes:
    """Build a one-page A4 PDF and return its bytes.

    Keeping the PDF in memory means the application does not depend on a
    persistent local filesystem. The caller stores the bytes in PostgreSQL.
    """
    buffer = BytesIO()
    qr_buffer = BytesIO(build_qr_png(event, token))

    page_w, page_h = A4
    pdf = canvas.Canvas(buffer, pagesize=A4)
    pdf.setTitle(f"Entry Pass - {registration.ticket_code}")

    margin = 42
    card_x, card_y = margin, 150
    card_w, card_h = page_w - margin * 2, page_h - 300
    pdf.setFillColor(colors.HexColor("#f4f7fb"))
    pdf.roundRect(card_x, card_y, card_w, card_h, 18, fill=1, stroke=0)
    pdf.setFillColor(colors.HexColor("#102a43"))
    pdf.roundRect(card_x, card_y + card_h - 105, card_w, 105, 18, fill=1, stroke=0)
    pdf.rect(card_x, card_y + card_h - 105, card_w, 18, fill=1, stroke=0)

    pdf.setFillColor(colors.white)
    pdf.setFont("Helvetica-Bold", 19)
    pdf.drawString(card_x + 24, card_y + card_h - 43, "EVENT ENTRY PASS")
    pdf.setFont("Helvetica", 9)
    pdf.drawString(card_x + 24, card_y + card_h - 64, "PRESENT THIS QR CODE AT THE EVENT GATE")

    text_x = card_x + 26
    y = card_y + card_h - 145
    pdf.setFillColor(colors.HexColor("#526579"))
    pdf.setFont("Helvetica-Bold", 8)
    pdf.drawString(text_x, y, "EVENT")
    pdf.setFillColor(colors.HexColor("#102a43"))
    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(text_x, y - 20, _fit_text(event.title, card_w - 55, "Helvetica-Bold", 14))

    y -= 58
    details = [
        ("PARTICIPANT", registration.full_name),
        ("TICKET ID", registration.ticket_code or "Pending"),
        ("CATEGORY", registration.category),
        ("INSTITUTION", registration.institution or "Not provided"),
        ("VENUE", event.venue),
        ("DATE & TIME", f"{event.start_at.strftime('%d %b %Y, %I:%M %p')} - {event.end_at.strftime('%I:%M %p')}"),
    ]
    qr_size = 142
    qr_x = card_x + card_w - qr_size - 28
    text_max_width = qr_x - text_x - 18
    for label, value in details:
        pdf.setFillColor(colors.HexColor("#718096"))
        pdf.setFont("Helvetica-Bold", 7)
        pdf.drawString(text_x, y, label)
        pdf.setFillColor(colors.HexColor("#243b53"))
        pdf.setFont("Helvetica", 9)
        pdf.drawString(text_x, y - 14, _fit_text(value, text_max_width, "Helvetica", 9))
        y -= 43

    qr_y = card_y + 105
    pdf.drawImage(ImageReader(qr_buffer), qr_x, qr_y, width=qr_size, height=qr_size, preserveAspectRatio=True, mask="auto")
    pdf.setFillColor(colors.HexColor("#526579"))
    pdf.setFont("Helvetica-Bold", 8)
    pdf.drawCentredString(qr_x + qr_size / 2, qr_y - 13, "SCAN AT ENTRY")

    pdf.setFillColor(colors.HexColor("#526579"))
    pdf.setFont("Helvetica", 8)
    pdf.drawString(card_x + 25, card_y + 32, "This ticket is valid for one successful check-in only.")
    pdf.drawString(card_x + 25, card_y + 19, "Keep this QR code private. A screenshot can be used as a ticket copy.")

    pdf.setFillColor(colors.HexColor("#718096"))
    pdf.setFont("Helvetica", 8)
    pdf.drawCentredString(page_w / 2, 95, "Generated by EventPass | Smart Event Registration & Entry Validation")
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()
